// The PostScript name Core Text resolves a name to: the name itself only when such a font is there.
std::string resolved(const char *postScriptName) {
  CTFontRef font = CTFontCreateWithName((__bridge CFStringRef)@(postScriptName), 12, nullptr);
  std::string name = ((__bridge_transfer NSString *)CTFontCopyPostScriptName(font)).UTF8String;
  CFRelease(font);
  return name;
}

