#!/usr/bin/env bash
# Generates a library's Fabric component codegen for the host build, the way React Native's
# Android build does for its C++ half, and prints the directory the CMake build reads it from.
#
#   codegen-library.sh <node_modules/react-native> <node_modules/library> [--modules]
#
# --modules is for an autolinked library (cmake/linked-modules.cmake), in <cache>/linked/<name>:
# its TurboModule spec's codegen, the <Name>JSI.h its C++ module implements, and when it declares
# Fabric components, their codegen and a library.cmake as below, which build.sh adds to the
# libraries it compiles in. A library with no codegen config prints nothing, since its module
# needs none.
#
# The directory, <cache>/libraries/<name>, holds:
#   codegen/react/renderer/components/<name>/   the codegen output (props, events, shadow nodes)
#   library.cmake                               what the build compiles and registers
#
# What a library declares for Android's C++ build is what the host uses: its codegen name
# (react-native.config.js's android.libraryName, or package.json's codegenConfig.name), its shared
# C++ in common/cpp/react/renderer/components/<name>, and the component descriptors it lists in
# react-native.config.js (every codegen descriptor when it lists none). A library with no codegen
# config is refused.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
RN_PKG="$(cd "${1:?usage: codegen-library.sh <react-native> <library>}" && pwd -P)"
LIB="$(cd "${2:?usage: codegen-library.sh <react-native> <library>}" && pwd -P)"
RN_VERSION="$(node -p "require('$RN_PKG/package.json').version")"
CACHE="$("$here/cache-dir.sh" "$RN_VERSION")"
modules=0
[ "${3:-}" = "--modules" ] && modules=1
if [ "$modules" = 1 ] && ! node -e 'process.exit(require(process.argv[1]).codegenConfig?.name ? 0 : 1)' "$LIB/package.json"; then
  exit 0
fi

# name, version and the descriptor list, one per line.
info="$(node -e '
  const path = require("path");
  const lib = process.argv[1];
  const pkg = require(path.join(lib, "package.json"));
  if (!pkg.codegenConfig?.name) {
    console.error(`codegen-library.sh: ${pkg.name} has no codegenConfig`);
    process.exit(1);
  }
  let android = {};
  try {
    android = require(path.join(lib, "react-native.config.js")).dependency?.platforms?.android ?? {};
  } catch {}
  console.log(android.libraryName ?? pkg.codegenConfig.name);
  console.log(`${pkg.name}@${pkg.version}`);
  console.log((android.componentDescriptors ?? []).join(";"));
' "$LIB")"
NAME="$(sed -n 1p <<< "$info")"
VERSION="$(sed -n 2p <<< "$info")"
DESCRIPTORS="$(sed -n 3p <<< "$info")"

OUT="$CACHE/libraries/$NAME"
[ "$modules" = 1 ] && OUT="$CACHE/linked/$NAME"
# The layout's own version last, so a cache written by an older script is made again.
STAMP="$VERSION $LIB 2"
if [ -f "$OUT/stamp" ] && [ "$(cat "$OUT/stamp")" = "$STAMP" ]; then
  echo "$OUT"
  exit 0
fi

echo "==> codegen $VERSION" >&2
tmp="$(mktemp -d)"
# The codegen also generates the library's own dependencies' specs; only its own are kept.
(cd "$RN_PKG" && node scripts/generate-codegen-artifacts.js -p "$LIB" -t android -o "$tmp" -s library) > "$tmp.log" 2>&1 || true
GEN="$tmp/android/app/build/generated/source/codegen/jni/react/renderer/components/$NAME"
if [ "$modules" = 1 ] && [ ! -f "$GEN/ComponentDescriptors.h" ]; then
  if [ ! -f "$GEN/${NAME}JSI.h" ]; then
    cat "$tmp.log" >&2
    echo "codegen-library.sh: the codegen wrote no module spec for $VERSION" >&2
    exit 1
  fi
  rm -rf "$OUT"
  mkdir -p "$OUT/codegen/react/renderer/components/$NAME"
  cp "$GEN"/*JSI.h "$OUT/codegen/react/renderer/components/$NAME/"
  echo "$STAMP" > "$OUT/stamp"
  rm -rf "$tmp" "$tmp.log"
  echo "$OUT"
  exit 0
fi
if [ ! -f "$GEN/ComponentDescriptors.h" ]; then
  cat "$tmp.log" >&2
  echo "codegen-library.sh: the codegen wrote no components for $VERSION" >&2
  exit 1
fi
if [ -z "$DESCRIPTORS" ]; then
  DESCRIPTORS="$(sed -n 's/^using \([A-Za-z0-9_]*ComponentDescriptor\) = .*/\1/p' "$GEN/ComponentDescriptors.h" | paste -sd ';' -)"
fi
COMMON="$LIB/common/cpp"
[ -d "$COMMON/react/renderer/components/$NAME" ] || COMMON=""

rm -rf "$OUT"
mkdir -p "$OUT/codegen/react/renderer/components"
cp -R "$GEN" "$OUT/codegen/react/renderer/components/"
cat > "$OUT/library.cmake" << EOF
# Generated by codegen-library.sh for $VERSION.
set(NGN_LIBRARY_NAME "$NAME")
set(NGN_LIBRARY_COMMON_DIR "$COMMON")
set(NGN_LIBRARY_DESCRIPTORS "$DESCRIPTORS")
EOF
echo "$STAMP" > "$OUT/stamp"
rm -rf "$tmp" "$tmp.log"
echo "$OUT"
