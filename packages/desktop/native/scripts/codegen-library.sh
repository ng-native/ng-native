#!/usr/bin/env bash
# Generates a library's Fabric component codegen for the host build, the way React Native's
# Android build does for its C++ half, and prints the directory the CMake build reads it from.
#
#   codegen-library.sh <node_modules/react-native> <node_modules/library> [--modules]
#
# --modules is for an autolinked library (cmake/linked-modules.cmake), in <cache>/linked/<name>-<key>:
# its TurboModule spec's codegen, the <Name>JSI.h its C++ module implements, and when it declares
# Fabric components, their codegen and a library.cmake as below, which build.sh adds to the
# libraries it compiles in. A library with no codegen config prints nothing, since its module
# needs none.
#
# The directory, <cache>/libraries/<name>-<key>, holds:
#   codegen/react/renderer/components/<name>/   the codegen output (props, events, shadow nodes)
#   library.cmake                               what the build compiles and registers
#
# <key> is a hash of the stamp: the library's name, version and folder, and this script's layout.
# Each directory is written under a temporary name and renamed into place once complete, and never
# changed after, so a build reading one is never handed another version's files halfway through.
#
# What a library declares for Android's C++ build is what the host uses: its codegen name
# (package.json's codegenConfig.name, which names the folder the codegen writes), its shared
# C++ in common/cpp/react/renderer/components/<name> (or the one other folder holding
# react/renderer/components/<name>, as react-native-gesture-handler's shared/shadowNodes, which
# declares the descriptor its codegen leaves out), and the component descriptors it lists in
# react-native.config.js (every codegen descriptor when it lists none). A library with no codegen
# config is refused.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
RN_PKG="$(cd "${1:?usage: codegen-library.sh <react-native> <library>}" && pwd -P)"
LIB="$(cd "${2:?usage: codegen-library.sh <react-native> <library>}" && pwd -P)"
RN_VERSION="$(node -p 'require(process.argv[1] + "/package.json").version' "$RN_PKG")"
CACHE="$("$here/cache-dir.sh" "$RN_VERSION")"
modules=0
[ "${3:-}" = "--modules" ] && modules=1

# The directory for a stamp: <parent>/<name>-<first 12 hex digits of the stamp's SHA-1>.
keyed() { printf '%s/%s-%s' "$1" "$2" "$(printf '%s' "$3" | shasum | cut -c1-12)"; }
# Moves a finished directory into place by one rename. When another run moved the same stamp's in
# first, that one is kept and this copy dropped.
# A directory being written, removed when the script stops before it is published.
STAGE=""
trap 'if [ -n "$STAGE" ]; then rm -rf "$STAGE"; fi' EXIT
publish() {
  node -e '
    const fs = require("fs");
    const [from, to] = process.argv.slice(1);
    try {
      fs.renameSync(from, to);
    } catch (error) {
      if (error.code !== "ENOTEMPTY" && error.code !== "EEXIST") throw error;
      fs.rmSync(from, { recursive: true, force: true });
    }
  ' "$1" "$2"
}

# A library the host builds by a recipe of its own (cmake/libraries/<package>.cmake), for its C++
# beyond Fabric components: react-native-worklets and react-native-reanimated. Its library.cmake names the recipe and the package, and no codegen
# runs: the host's glue implements the modules by hand, and their components are not registered.
PKG_NAME="$(node -p 'require(process.argv[1]).name' "$LIB/package.json")"
RECIPE="$here/../cmake/libraries/$PKG_NAME.cmake"
if [ "$modules" = 0 ] && [ -f "$RECIPE" ]; then
  VERSION="$(node -p 'const p = require(process.argv[1]); `${p.name}@${p.version}`' "$LIB/package.json")"
  STAMP="$VERSION $LIB recipe 2"
  OUT="$(keyed "$CACHE/libraries" "$PKG_NAME" "$STAMP")"
  if [ ! -f "$OUT/stamp" ]; then
    STAGE="$OUT.partial.$$"
    rm -rf "$STAGE"
    mkdir -p "$STAGE"
    # Its components' codegen (props, events, shadow nodes), when it declares any: the library's
    # C++ includes their headers, as Reanimated does its own.
    CODEGEN_NAME="$(node -p 'const p = require(process.argv[1]); p.codegenConfig && p.codegenConfig.type !== "modules" ? p.codegenConfig.name : ""' "$LIB/package.json")"
    if [ -n "$CODEGEN_NAME" ]; then
      echo "==> codegen $VERSION" >&2
      tmp="$(mktemp -d)"
      (cd "$RN_PKG" && node scripts/generate-codegen-artifacts.js -p "$LIB" -t android -o "$tmp" -s library) > "$tmp.log" 2>&1 || true
      GEN="$tmp/android/app/build/generated/source/codegen/jni/react/renderer/components/$CODEGEN_NAME"
      if [ ! -f "$GEN/Props.h" ]; then
        cat "$tmp.log" >&2
        echo "codegen-library.sh: the codegen wrote no components for $VERSION" >&2
        exit 1
      fi
      mkdir -p "$STAGE/codegen/react/renderer/components"
      cp -R "$GEN" "$STAGE/codegen/react/renderer/components/"
      rm -rf "$tmp" "$tmp.log"
    fi
    cat > "$STAGE/library.cmake" << EOF
# Generated by codegen-library.sh for $VERSION.
set(NGN_LIBRARY_NAME "$PKG_NAME")
set(NGN_LIBRARY_RECIPE "$(cd "$(dirname "$RECIPE")" && pwd -P)/$PKG_NAME.cmake")
set(NGN_LIBRARY_PACKAGE_DIR "$LIB")
set(NGN_LIBRARY_CODEGEN "${CODEGEN_NAME:+$OUT/codegen}")
set(NGN_LIBRARY_CODEGEN_NAME "$CODEGEN_NAME")
EOF
    echo "$STAMP" > "$STAGE/stamp"
    publish "$STAGE" "$OUT"
  fi
  echo "$OUT"
  exit 0
fi
if [ "$modules" = 1 ] && ! node -e 'process.exit(require(process.argv[1]).codegenConfig?.name ? 0 : 1)' "$LIB/package.json"; then
  exit 0
fi

# name, version and the descriptor list, one per line.
info="$(node -e '
  const path = require("path");
  const lib = process.argv[1];
  const pkg = require(path.join(lib, "package.json"));
  if (!pkg.codegenConfig?.name) {
    console.error(`codegen-library.sh: ${pkg.name} has no codegenConfig`);
    process.exit(1);
  }
  let android = {};
  try {
    android = require(path.join(lib, "react-native.config.js")).dependency?.platforms?.android ?? {};
  } catch {}
  // The codegen writes into a folder named by codegenConfig.name, which the C++ of the library
  // includes too; android.libraryName names only its Android build target.
  console.log(pkg.codegenConfig.name);
  console.log(`${pkg.name}@${pkg.version}`);
  console.log((android.componentDescriptors ?? []).join(";"));
' "$LIB")"
NAME="$(sed -n 1p <<< "$info")"
VERSION="$(sed -n 2p <<< "$info")"
DESCRIPTORS="$(sed -n 3p <<< "$info")"

# The layout's own version last, so a cache written by an older script is made again.
STAMP="$VERSION $LIB 3"
OUT="$(keyed "$CACHE/libraries" "$NAME" "$STAMP")"
[ "$modules" = 1 ] && OUT="$(keyed "$CACHE/linked" "$NAME" "$STAMP")"
if [ -f "$OUT/stamp" ]; then
  echo "$OUT"
  exit 0
fi
STAGE="$OUT.partial.$$"
rm -rf "$STAGE"

echo "==> codegen $VERSION" >&2
tmp="$(mktemp -d)"
# The codegen also generates the library's own dependencies' specs; only its own are kept.
(cd "$RN_PKG" && node scripts/generate-codegen-artifacts.js -p "$LIB" -t android -o "$tmp" -s library) > "$tmp.log" 2>&1 || true
GEN="$tmp/android/app/build/generated/source/codegen/jni/react/renderer/components/$NAME"
if [ "$modules" = 1 ] && [ ! -f "$GEN/ComponentDescriptors.h" ]; then
  if [ ! -f "$GEN/${NAME}JSI.h" ]; then
    cat "$tmp.log" >&2
    echo "codegen-library.sh: the codegen wrote no module spec for $VERSION" >&2
    exit 1
  fi
  mkdir -p "$STAGE/codegen/react/renderer/components/$NAME"
  cp "$GEN"/*JSI.h "$STAGE/codegen/react/renderer/components/$NAME/"
  echo "$STAMP" > "$STAGE/stamp"
  publish "$STAGE" "$OUT"
  rm -rf "$tmp" "$tmp.log"
  echo "$OUT"
  exit 0
fi
if [ ! -f "$GEN/ComponentDescriptors.h" ]; then
  cat "$tmp.log" >&2
  echo "codegen-library.sh: the codegen wrote no components for $VERSION" >&2
  exit 1
fi
if [ -z "$DESCRIPTORS" ]; then
  DESCRIPTORS="$(sed -n 's/^using \([A-Za-z0-9_]*ComponentDescriptor\) = .*/\1/p' "$GEN/ComponentDescriptors.h" | paste -sd ';' -)"
fi
# The library's own C++ beside its codegen: common/cpp, or else the folder in the package (outside
# its build output, dependencies and other platforms' sources) that holds
# react/renderer/components/<name>.
COMMON=""
if [ -d "$LIB/common/cpp/react/renderer/components/$NAME" ]; then
  COMMON="$LIB/common/cpp"
else
  found="$(cd "$LIB" && find . \( -name node_modules -o -name build -o -name lib -o -name android -o -name ios -o -name apple -o -name macos -o -name windows \) -prune \
    -o -type d -path "*/react/renderer/components/$NAME" -print)"
  found="${found%%$'\n'*}"
  if [ -n "$found" ]; then
    COMMON="$LIB/${found#./}"
    COMMON="${COMMON%/react/renderer/components/$NAME}"
  fi
fi

mkdir -p "$STAGE/codegen/react/renderer/components"
cp -R "$GEN" "$STAGE/codegen/react/renderer/components/"
cat > "$STAGE/library.cmake" << EOF
# Generated by codegen-library.sh for $VERSION.
set(NGN_LIBRARY_NAME "$NAME")
set(NGN_LIBRARY_COMMON_DIR "$COMMON")
set(NGN_LIBRARY_DESCRIPTORS "$DESCRIPTORS")
EOF
echo "$STAMP" > "$STAGE/stamp"
publish "$STAGE" "$OUT"
rm -rf "$tmp" "$tmp.log"
echo "$OUT"
