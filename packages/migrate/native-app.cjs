/** Java's reserved words, which Android refuses as a segment of a package name. */
const JAVA_KEYWORDS = new Set(
  (
    'abstract assert boolean break byte case catch char class const continue default do double ' +
    'else enum extends false final finally float for goto if implements import instanceof int ' +
    'interface long native new null package private protected public return short static ' +
    'strictfp super switch synchronized this throw throws transient true try void volatile while'
  ).split(' '),
);

/**
 * Kotlin's hard keywords, which it refuses as a package segment as Java refuses its own: Expo
 * writes the Android package into `MainActivity.kt` and `MainApplication.kt` without escaping one.
 */
const KOTLIN_KEYWORDS = new Set(
  (
    'as break class continue do else false for fun if in interface is null object package return ' +
    'super this throw true try typealias typeof val var when while'
  ).split(' '),
);

/** Whether `segment` is a keyword Java or Kotlin refuses as a package segment. */
const isKeyword = (segment) => JAVA_KEYWORDS.has(segment) || KOTLIN_KEYWORDS.has(segment);

/**
 * Whether iOS takes `id` as a bundle identifier and Android as a package name: two or more
 * segments, each a letter and then letters or digits (iOS refuses `_`, Android `-`), none of them
 * a Java or Kotlin keyword.
 *
 * @param {string} id
 */
function isBundleIdentifier(id) {
  const segments = id.split('.');
  return segments.length > 1 && segments.every((s) => /^[a-z][a-z0-9]*$/i.test(s) && !isKeyword(s));
}

/**
 * Why `id` cannot be the app's bundle identifier, as a sentence, or `undefined` when it can.
 *
 * @param {string} id
 */
function bundleIdentifierProblem(id) {
  if (isBundleIdentifier(id)) return undefined;
  return (
    `${id} is not a bundle identifier both iOS and Android accept: ` +
    'two or more dot-separated segments, each a letter and then letters or digits, none a Java or ' +
    'Kotlin keyword.'
  );
}

/**
 * `com.<scope>.<name>`, for an app given no `--bundleIdentifier`, where prebuild would otherwise
 * make it `com.anonymous.<name>`. The scope is left out when it cannot be made a segment.
 *
 * @param {string} name the app's name, without a scope
 * @param {string | undefined} scope the workspace's npm scope, `@acme`
 */
function bundleIdentifier(name, scope) {
  const clean = (text) => text.toLowerCase().replace(/[^a-z0-9]/g, '');
  const valid = (segment) => /^[a-z]/.test(segment) && !isKeyword(segment);
  const org = clean(scope ?? '');
  const app = clean(name);
  return ['com', ...(valid(org) ? [org] : []), valid(app) ? app : `app${app}`].join('.');
}

/** The OSes a desktop app runs on, in the order its `platforms` lists them. */
const DESKTOP_OSES = ['macos', 'linux'];

/** The package that builds and packages the desktop app, and its config plugin's name. */
const DESKTOP_PACKAGE = '@ng-native/desktop';

/** What a desktop app adds to its dependencies: the host and the `ng-native-desktop` command. */
const desktopDependencies = { [DESKTOP_PACKAGE]: version };

/**
 * A desktop-only app's dependencies, the desktop template's: the mobile app's, less the two that
 * only set up a phone's status bar and system UI, with the desktop host and `@ng-native/expo`, whose
 * services the desktop starter uses. A host library is pinned to the prebuilt host's version.
 *
 * @type {Record<string, string>}
 */
const desktopOnlyDependencies = Object.fromEntries(
  Object.entries({
    ...dependencies,
    ...desktopDependencies,
    '@ng-native/expo': version,
    // Exactly the version the prebuilt desktop host is built with, so the app runs on it.
    'react-native-safe-area-context': '5.11.1',
  })
    .filter(([name]) => name !== 'expo-status-bar' && name !== 'expo-system-ui')
    .sort(([a], [b]) => (a < b ? -1 : 1)),
);

/**
 * What a desktop-only app lacks of a mobile app's dependencies, which adding iOS and Android back
 * adds: the phone's status bar and system UI packages.
 *
 * @type {Record<string, string>}
 */
const mobileDependencies = Object.fromEntries(
  Object.entries(dependencies).filter(([name]) => !(name in desktopOnlyDependencies)),
);

/**
 * The scripts a desktop app adds: `npm run macos` and `npm run linux` build the host and open the
 * app from the dev server `npm start` runs, and `npm run package` makes the `.app`, `.dmg` or Mac
 * App Store package, or on Linux the `app`, `deb`, `rpm` or `flatpak` one. The Expo CLI has no
 * `run:macos` or `run:linux`: its `run` commands are a fixed list.
 */
const DESKTOP_SCRIPTS = {
  macos: 'ng-native-desktop run',
  linux: 'ng-native-desktop run --os linux',
  package: 'ng-native-desktop package',
};

/** What `ng-native-desktop package` writes into the app's directory, for its `.gitignore`. */
